const TABLE: Record<Lang, Record<Key, string>> = { en, de }

/** Die Sprache der Meldungen aus der Option `ui_language`; alles Unbekannte ergibt Englisch. */
export function parseLang(option: unknown): Lang {
  return String(option ?? '').trim().toLowerCase() === 'de' ? 'de' : 'en'
}

/** Eine Meldung in der Sprache `lang`; `{name}` wird durch `params.name` ersetzt. */
export function msg(lang: Lang, key: Key, params: Record<string, string | number> = {}): string {
  const text = (TABLE[lang] ?? en)[key]
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole))
}
